import { FormField, type FieldConfig, type KeyValueEntry } from '@invana/forms';
import { Button, Eyebrow, cn } from '@invana/ui';
import { FormProvider, useForm, type Control, type FieldValues } from 'react-hook-form';

/** The values a {@link PropertiesEditor} edits: a label + a flat string→string data map. */
export interface PropertiesEditorValues {
  /** The element's label text. */
  label: string;
  /** The element's free-form type tag (maps to `node.type` / `edge.type`). Only edited when `showType`. */
  type?: string;
  /** Arbitrary key/value metadata (maps to `node.data` / `edge.data`). */
  data: Record<string, string>;
}

export interface PropertiesEditorProps {
  /** Heading shown above the form, e.g. `'Node'` / `'Relationship'`. */
  title?: string;
  /**
   * Initial values, loaded into the form **once** on mount. To reload for a
   * different element, remount via `key`.
   */
  defaults?: Partial<PropertiesEditorValues>;
  /** Called with the edited values when the user clicks Apply. */
  onSubmit: (values: PropertiesEditorValues) => void;
  /** Submit button label. Default `'Apply'`. */
  submitLabel?: string;
  /** Show the label field. Default `true`. */
  showLabel?: boolean;
  /** Show an editable `type` field above the properties list. Default `false`. */
  showType?: boolean;
  /**
   * When provided, render a "Reverse direction" button in the footer that
   * invokes this callback immediately (i.e. not on Apply). Used for edges to
   * swap source/target. Omit for elements that have no direction.
   */
  onReverse?: () => void;
  /** When provided, a *Cancel* beside Apply that leaves without saving. */
  onCancel?: () => void;
  /** Class on the root — merged over the base classes via `cn`. */
  className?: string;
}

/** The form's state: the editor's values with `data` as rows, so a blank or repeated key can be typed. */
interface EditorForm {
  element: { label: string; type: string; properties: KeyValueEntry[] };
}

/** The fields, generated by `@invana/forms` — label and type when shown, then the properties list. */
function fieldsFor(showLabel: boolean, showType: boolean): FieldConfig[] {
  return [
    ...(showLabel ? [{ name: 'label', type: 'text', label: 'Label', placeholder: 'Label text' } as FieldConfig] : []),
    ...(showType ? [{ name: 'type', type: 'text', label: 'Type', placeholder: 'Type' } as FieldConfig] : []),
    {
      name: 'properties',
      type: 'keyvalue',
      label: 'Properties',
      keyPlaceholder: 'Name',
      valuePlaceholder: 'Value',
      addLabel: 'Add property',
      emptyLabel: 'No properties yet.',
    },
  ];
}

/**
 * Dumb, engine-agnostic editor for an element's **label, type and key/value
 * properties**. The form is generated by `@invana/forms` from a `FieldConfig[]`
 * — `text` fields for the label and type, a `keyvalue` field for the properties
 * — so it reads like every other generated form.
 *
 * Props in / `onSubmit` out: it owns the form state and on Apply emits
 * `{ label, data }` (plus `type` when `showType`). It holds **no** engine /
 * layer / commit logic — the consumer (see {@link InspectorPanel}) wires
 * `onSubmit` to the store. Blank-keyed rows are dropped on submit; on duplicate
 * keys the last row wins.
 *
 * It draws no card of its own: it sits inside whatever frames it — a board's
 * rail panel, or `InspectorPanel`'s floating `<Panel>`.
 */
export function PropertiesEditor({
  title,
  defaults,
  onSubmit,
  submitLabel = 'Apply',
  showLabel = true,
  showType = false,
  onReverse,
  onCancel,
  className,
}: PropertiesEditorProps) {
  const form = useForm<EditorForm>({
    defaultValues: {
      element: {
        label: defaults?.label ?? '',
        type: defaults?.type ?? '',
        properties: Object.entries(defaults?.data ?? {}).map(([key, value]) => ({ key, value })),
      },
    },
  });

  const apply = (): void => {
    const { label, type, properties } = form.getValues('element');
    const data: Record<string, string> = {};
    for (const { key, value } of properties) {
      const k = key.trim();
      if (k) data[k] = value;
    }
    onSubmit(showType ? { label, type, data } : { label, data });
  };

  // Widen at the boundary — RHF's typed Control isn't assignable to ObjectField's
  // `Control<any>` (the field-name union is contravariant).
  const control = form.control as unknown as Control<FieldValues>;

  return (
    <FormProvider {...form}>
      <div className={cn('flex min-w-[240px] flex-col gap-3 p-3', className)}>
        {title && <Eyebrow>{title}</Eyebrow>}
        <FormField.ObjectField
          control={control}
          columns={1}
          labelPosition="top"
          size="xs"
          name="element"
          fields={fieldsFor(showLabel, showType)}
        />
        <div className={cn('flex flex-wrap items-center gap-1.5', onReverse ? 'justify-between' : 'justify-end')}>
          {onReverse && (
            <Button variant="outline" size="sm" onClick={onReverse}>
              Reverse direction
            </Button>
          )}
          <div className="ml-auto flex items-center gap-1.5">
            {onCancel && (
              <Button variant="ghost" size="sm" onClick={onCancel}>
                Cancel
              </Button>
            )}
            <Button size="sm" onClick={apply}>
              {submitLabel}
            </Button>
          </div>
        </div>
      </div>
    </FormProvider>
  );
}
