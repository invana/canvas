import { FormField, type FieldConfig, type KeyValueEntry } from '@invana/forms';
import { Alert, AlertDescription, Button, Eyebrow, PropertyList, PropertyRow, cn } from '@invana/ui';
import { ArrowUpDown, TriangleAlert } from 'lucide-react';
import { useEffect, useRef, useState, type ReactNode } from 'react';
import { FormProvider, useForm, useWatch, type Control, type FieldValues } from 'react-hook-form';

/** One property key a type has in the model, and the kind of value it takes (`text`, `number`, `date`…). */
export interface ElementSchemaKey {
  key: string;
  kind?: string;
}

/** One type in the model — a node label or a relationship type — and its property keys. */
export interface ElementTypeSchema {
  type: string;
  keys: ElementSchemaKey[];
}

/** The values a {@link ElementEditorPanel} edits: a label + a flat string→string data map. */
export interface ElementEditorValues {
  /** The element's label text. */
  label: string;
  /** The element's free-form type tag (maps to `node.type` / `edge.type`). Only edited when `showType`. */
  type?: string;
  /** Arbitrary key/value metadata (maps to `node.data` / `edge.data`). */
  data: Record<string, string>;
}

export interface ElementEditorPanelProps {
  /** Heading shown above the form, e.g. `'Node'` / `'Relationship'`. */
  title?: string;
  /**
   * Initial values, loaded into the form **once** on mount. To reload for a
   * different element, remount via `key`.
   */
  defaults?: Partial<ElementEditorValues>;
  /** Called with the edited values when the user clicks Apply. */
  onSubmit: (values: ElementEditorValues) => void;
  /** Submit button label. Default `'Apply'`. */
  submitLabel?: string;
  /** Show the label field. Default `true`. */
  showLabel?: boolean;
  /** Show an editable `type` field above the properties list. Default `false`. */
  showType?: boolean;
  /**
   * The type must be given: set, the Type field comes first with the caret in
   * it, and Apply refuses a blank one with this message under the field. For an
   * element just drawn — a type cannot be guessed. Implies `showType`.
   */
  requireType?: string;
  /** Types offered as the Type field is typed — the ones already on the board. Any other is accepted. */
  typeSuggestions?: string[];
  /**
   * The model's types for this kind of element, each with its property keys.
   * Picking a type fills its keys as rows; *Add property* lists the keys not
   * set yet, and a value's placeholder is its key's kind.
   */
  schema?: ElementTypeSchema[];
  /**
   * Take only what `schema` has: the type is picked from its types, and a key
   * from that type's keys. Default `false` — the schema's are offered and any
   * other may be typed (tagged *new*).
   */
  strictSchema?: boolean;
  /**
   * A relationship's ends, shown read-only above the fields — drawing fixed
   * them; another pair is another relationship.
   */
  endpoints?: { from: ReactNode; to: ReactNode };
  /**
   * When provided, a *Reverse direction* act beside the endpoints (or in the
   * footer without them) that swaps source and target at once, not on Apply.
   * Omit for elements that have no direction.
   */
  onReverse?: () => void;
  /** When provided, a *Cancel* beside Apply that leaves without saving. */
  onCancel?: () => void;
  /**
   * When provided, a *Reset* that puts the form back to `defaults` (or to
   * `values`, when controlled), then tells the host.
   */
  onReset?: () => void;
  /** When provided, a *Delete* at the foot's left — the host removes the element. */
  onDelete?: () => void;
  /**
   * Controlled values: when they change, the form shows them. Pair with
   * `onChange` to drive the editor from outside — a test, a script, a host's
   * own state.
   */
  values?: Partial<ElementEditorValues>;
  /** Every edit, as the values Apply would send. */
  onChange?: (values: ElementEditorValues) => void;
  /** Class on the root — merged over the base classes via `cn`. */
  className?: string;
}

/** The form's state: the editor's values with `data` as rows, so a blank or repeated key can be typed. */
interface EditorForm {
  element: { label: string; type: string; properties: KeyValueEntry[] };
}

interface FieldsOptions {
  showLabel: boolean;
  showType: boolean;
  requireType?: string | undefined;
  typeSuggestions: string[];
  types: string[];
  keys: ElementSchemaKey[];
  strict: boolean;
}

/**
 * The fields, generated by `@invana/forms` — label and type when shown (type
 * first when required), then the properties list, its keys those of the type
 * picked.
 */
function fieldsFor({ showLabel, showType, requireType, typeSuggestions, types, keys, strict }: FieldsOptions): FieldConfig[] {
  const label = showLabel ? [{ name: 'label', type: 'text', label: 'Label', placeholder: 'Label text' } as FieldConfig] : [];
  const required = requireType ? { rules: { validate: (v: unknown) => (typeof v === 'string' && v.trim() !== '') || requireType } } : {};
  const pick = strict && types.length > 0;
  const offered = [...new Set([...types, ...typeSuggestions])];
  const type: FieldConfig[] = showType
    ? [
        pick
          ? ({ name: 'type', type: 'select', label: 'Type', placeholder: 'Pick a type', options: types.map((t) => ({ label: t, value: t })), ...required } as FieldConfig)
          : ({
              name: 'type',
              type: 'text',
              label: 'Type',
              placeholder: requireType ? 'Pick or type a type' : 'Type',
              ...(offered.length ? { options: offered.map((t) => ({ label: t, value: t })) } : {}),
              ...(requireType ? { autoFocus: true } : {}),
              ...required,
            } as FieldConfig),
      ]
    : [];
  return [
    ...(requireType ? [...type, ...label] : [...label, ...type]),
    {
      name: 'properties',
      type: 'keyvalue',
      label: 'Properties',
      keyPlaceholder: 'Key',
      valuePlaceholder: 'Value',
      addLabel: 'Add property',
      emptyLabel: requireType && keys.length === 0 && pick ? 'Pick a type to see its keys.' : 'No properties yet.',
      ...(keys.length ? { options: keys.map((k) => ({ label: k.key, value: k.key, ...(k.kind ? { description: k.kind } : {}) })) } : {}),
      ...(strict ? { strictKeys: true } : {}),
    },
  ];
}

/** The form's state for `v` — `data` as rows, so a blank or repeated key can be typed. */
function formOf(v: Partial<ElementEditorValues> | undefined): EditorForm {
  return {
    element: {
      label: v?.label ?? '',
      type: v?.type ?? '',
      properties: Object.entries(v?.data ?? {}).map(([key, value]) => ({ key, value })),
    },
  };
}

/** The form's state as Apply sends it: a blank key or a blank value is not kept. */
function valuesOf(element: EditorForm['element'], withType: boolean): ElementEditorValues {
  const data: Record<string, string> = {};
  for (const { key, value } of element.properties ?? []) {
    const k = (key ?? '').trim();
    if (k && (value ?? '').trim() !== '') data[k] = value;
  }
  const label = element.label ?? '';
  return withType ? { label, type: (element.type ?? '').trim(), data } : { label, data };
}

/**
 * The rows for a newly picked type: strict, exactly its keys (a value carried
 * over where the key was set); open, what is there plus its keys not set yet.
 */
function rowsForType(rows: KeyValueEntry[], keys: ElementSchemaKey[], strict: boolean): KeyValueEntry[] {
  const value = new Map(rows.map((r) => [r.key.trim(), r.value]));
  if (strict) return keys.map((k) => ({ key: k.key, value: value.get(k.key) ?? '' }));
  const have = new Set(rows.map((r) => r.key.trim()));
  return [...rows, ...keys.filter((k) => !have.has(k.key)).map((k) => ({ key: k.key, value: '' }))];
}

/**
 * The editor for one drawn element — a node or a relationship: its **type, label,
 * ends and key/value properties**. The form is generated by `@invana/forms` from
 * a `FieldConfig[]` — `text` fields for the label and type, a `keyvalue` field for
 * the properties — so it reads like every other generated form.
 *
 * Props in / `onSubmit` out: it owns the form state and on Apply emits
 * `{ label, data }` (plus `type` when `showType`). It holds **no** engine /
 * layer / commit logic — the consumer (`ElementViewPanel`) wires `onSubmit` to
 * the store. A row with a blank key or a blank value is not saved; a key appears
 * once — a repeat is refused at its row and Apply waits.
 *
 * **Keys from the model.** Given `schema`, the keys follow the type: picking a
 * type fills its keys as rows, and changing it swaps them — with
 * `strictSchema`, the rows become exactly the new type's keys and the ones it
 * lacks are named as dropped on Apply. `strictSchema` also makes the type a
 * pick from the model's types and allows no key of one's own.
 *
 * It draws no card of its own: it sits inside whatever frames it — a board's
 * rail panel, or a floating `<Panel>`.
 */
export function ElementEditorPanel({
  title,
  defaults,
  onSubmit,
  submitLabel = 'Apply',
  showLabel = true,
  showType: showTypeProp = false,
  requireType,
  typeSuggestions = [],
  schema,
  strictSchema = false,
  endpoints,
  onReverse,
  onCancel,
  onReset,
  onDelete,
  values,
  onChange,
  className,
}: ElementEditorPanelProps) {
  const showType = showTypeProp || !!requireType;
  const form = useForm<EditorForm>({ defaultValues: formOf(values ?? defaults) });

  // Controlled: new `values` replace what the form shows.
  const valuesKey = values ? JSON.stringify(values) : null;
  useEffect(() => {
    if (valuesKey !== null) form.reset(formOf(JSON.parse(valuesKey) as Partial<ElementEditorValues>));
  }, [valuesKey, form]);

  // Every edit, as Apply would send it.
  const changed = useRef(onChange);
  changed.current = onChange;
  useEffect(() => {
    const sub = form.watch((all) => {
      const el = (all as EditorForm).element;
      if (el && changed.current) changed.current(valuesOf(el, showTypeProp || !!requireType));
    });
    return () => sub.unsubscribe();
  }, [form, showTypeProp, requireType]);

  const types = schema?.map((t) => t.type) ?? [];
  const keysOf = (type: string): ElementSchemaKey[] => schema?.find((t) => t.type === type.trim())?.keys ?? [];
  const strict = strictSchema && !!schema;

  // The keys follow the type: a type picked (or changed) here refills the rows.
  const watchedType = useWatch({ control: form.control, name: 'element.type' }) ?? '';
  const lastType = useRef(watchedType);
  const [dropped, setDropped] = useState<string[]>([]);
  useEffect(() => {
    if (watchedType === lastType.current) return;
    lastType.current = watchedType;
    const keys = keysOf(watchedType);
    if (keys.length === 0 && !strict) return;
    const rows = form.getValues('element.properties');
    const next = rowsForType(rows, keys, strict);
    const kept = new Set(next.map((r) => r.key));
    setDropped(rows.filter((r) => r.key.trim() && r.value.trim() && !kept.has(r.key.trim())).map((r) => r.key.trim()));
    form.setValue('element.properties', next, { shouldDirty: true });
    // keysOf reads `schema`; a new schema mid-edit does not refill.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [watchedType, strict]);

  const apply = ({ element }: EditorForm): void => onSubmit(valuesOf(element, showType));
  const reset = (): void => {
    form.reset(formOf(values ?? defaults));
    setDropped([]);
    onReset?.();
  };

  // Widen at the boundary — RHF's typed Control isn't assignable to ObjectField's
  // `Control<any>` (the field-name union is contravariant).
  const control = form.control as unknown as Control<FieldValues>;

  return (
    <FormProvider {...form}>
      <div className={cn('flex min-w-[240px] flex-col gap-3 p-3', className)}>
        {title && <Eyebrow>{title}</Eyebrow>}
        {endpoints && (
          <div className="flex items-center gap-1">
            <PropertyList labelWidth="auto" variant="summary" className="min-w-0 flex-1">
              <PropertyRow label="From">{endpoints.from}</PropertyRow>
              <PropertyRow label="To">{endpoints.to}</PropertyRow>
            </PropertyList>
            {onReverse && (
              <Button variant="ghost" size="icon-sm" aria-label="Reverse direction" title="Reverse direction" onClick={onReverse}>
                <ArrowUpDown />
              </Button>
            )}
          </div>
        )}
        <FormField.ObjectField
          control={control}
          columns={1}
          labelPosition="top"
          size="xs"
          name="element"
          fields={fieldsFor({ showLabel, showType, requireType, typeSuggestions, types, keys: keysOf(watchedType), strict })}
        />
        {dropped.length > 0 && (
          <Alert tone="warning" role="status">
            <TriangleAlert />
            <AlertDescription>
              A {watchedType} takes other keys: {dropped.join(', ')} {dropped.length === 1 ? 'is' : 'are'} dropped on Apply.
            </AlertDescription>
          </Alert>
        )}
        <div className={cn('flex flex-wrap items-center gap-1.5', onReverse && !endpoints ? 'justify-between' : 'justify-end')}>
          {onReverse && !endpoints && (
            <Button variant="outline" size="sm" onClick={onReverse}>
              Reverse direction
            </Button>
          )}
          {onDelete && (
            <Button variant="ghost" size="sm" className="text-destructive" onClick={onDelete}>
              Delete
            </Button>
          )}
          <div className="ml-auto flex items-center gap-1.5">
            {onReset && (
              <Button variant="ghost" size="sm" onClick={reset}>
                Reset
              </Button>
            )}
            {onCancel && (
              <Button variant="ghost" size="sm" onClick={onCancel}>
                Cancel
              </Button>
            )}
            <Button size="sm" onClick={() => void form.handleSubmit(apply)()}>
              {submitLabel}
            </Button>
          </div>
        </div>
      </div>
    </FormProvider>
  );
}
